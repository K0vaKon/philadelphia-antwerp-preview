const languageNames = { ru: "RU", nl: "NL", en: "EN" };
const savedLanguage = localStorage.getItem("philadelphia-language") || "ru";
const languageSelect = document.createElement("select");
languageSelect.className = "language-switcher";
languageSelect.setAttribute("aria-label", "Выбор языка");
Object.entries(languageNames).forEach(([code, name]) => {
  const option = document.createElement("option");
  option.value = code;
  option.textContent = name;
  languageSelect.append(option);
});
languageSelect.value = savedLanguage;
document.querySelectorAll(".site-header").forEach((header) => header.insertBefore(languageSelect.cloneNode(true), header.querySelector(".menu-toggle") || header.lastElementChild));

const translateTextNodes = (language) => {
  const dictionary = translations[language];
  const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
  const nodes = [];
  while (walker.nextNode()) nodes.push(walker.currentNode);
  nodes.forEach((node) => {
    const value = node.nodeValue.trim();
    if (dictionary[value]) node.nodeValue = node.nodeValue.replace(value, dictionary[value]);
  });
  document.querySelectorAll(".language-switcher").forEach((select) => { select.value = language; });
  document.querySelectorAll("input[placeholder], textarea[placeholder]").forEach((input) => {
    const placeholder = input.getAttribute("placeholder");
    const placeholderTranslations = {
      "Например, Вечер хвалы": { nl: "Bijvoorbeeld: Avond van aanbidding", en: "For example: Worship evening" },
      "Праздник, собрание, молодёжь": { nl: "Feest, samenkomst, jongeren", en: "Celebration, gathering, youth" },
      "Расскажите, что будет на событии": { nl: "Vertel wat er tijdens het evenement gebeurt", en: "Describe what will happen at the event" },
      "Введите пароль": { nl: "Voer wachtwoord in", en: "Enter password" }
    };
    if (placeholderTranslations[placeholder]?.[language]) input.placeholder = placeholderTranslations[placeholder][language];
  });
  document.documentElement.lang = language;
  const titles = {
    ru: { "index.html": "Филадельфия — церковь в Антверпене", "about.html": "О нас — Филадельфия", "leaders.html": "Служения — Филадельфия", "admin.html": "Админка событий — Филадельфия" },
    nl: { "index.html": "Philadelphia — kerk in Antwerpen", "about.html": "Over ons — Philadelphia", "leaders.html": "Bedieningen — Philadelphia", "admin.html": "Evenementenbeheer — Philadelphia" },
    en: { "index.html": "Philadelphia — church in Antwerp", "about.html": "About us — Philadelphia", "leaders.html": "Ministries — Philadelphia", "admin.html": "Event admin — Philadelphia" }
  };
  const page = location.pathname.split("/").pop() || "index.html";
  if (titles[language]?.[page]) document.title = titles[language][page];
};

document.querySelectorAll(".language-switcher").forEach((select) => {
  select.addEventListener("change", (event) => {
    localStorage.setItem("philadelphia-language", event.target.value);
    window.location.reload();
  });
});

translateTextNodes(savedLanguage);
